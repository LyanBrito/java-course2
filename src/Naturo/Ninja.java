package Naturo;

import java.util.List;

abstract class Ninja {
    private String nome;
    private int idade;
    private String vilaOrigem;
    private int nivelChakra;
    private int exp;
    private List<String> jutsus;
    private String tipoChakraPrim;
    private boolean possuiKekkeiGenkai;
    private int velocidade;
    private int forca;
    private int inteligencia;
    private String cla;

    abstract void aprenterJutsus();
}
